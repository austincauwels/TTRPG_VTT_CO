// Imogen (desktop) takes her own Body mark: log line; Jonah (phone) Behind Me card lasts past 20 s;
// Edda (tablet) Premonitions; Jonah intercepts after 35 s
const L = require('./r8405_lib'); const H = require('./r8405_h');
const { sleep, state } = L;
const card = (p) => p.$$eval('[role=alertdialog]', ds => ds.map(d => d.innerText.replace(/\s+/g, ' ')));
(async () => {
  const b = await L.launch();
  for (const k of ['a', 'b', 'c', 'd']) L.resetChar(state.chars[k].id, k === 'a' ? { intuition_current: 5 } : {});
  const lk = await L.openSeat(b, 'wide', { store: await L.storeFor('lk', null, 'S') });
  const a = await L.openSeat(b, 'desktop', { store: await L.storeFor('pa', 'a', 'S') });
  const j = await L.openSeat(b, 'phone', { store: await L.storeFor('pb', 'b', 'S') });
  const d = await L.openSeat(b, 'tablet', { store: await L.storeFor('pd', 'd', 'S') });
  await sleep(4500);
  const n0 = (await H.log(lk.page)).length;
  await a.page.locator('button[aria-label="Take Body mark 1 of 3"]').click();
  await sleep(800);
  console.log('Imogen during Undo', await L.trackState(a.page, 'Body'));
  console.log('Undo strip', await a.page.locator('text=/Undo runs out/').first().innerText().catch(() => 'none'));
  await L.shot(a.page, 'g01_imogen_undo', { clip: { x: 400, y: 700, width: 1020, height: 200 } });
  await sleep(6500);
  console.log('Imogen after Undo', await L.trackState(a.page, 'Body'), H.char(state.chars.a.id).body_marks);
  console.log('LK new lines', (await H.log(lk.page)).slice(n0));
  console.log('Jonah card at ~1s', await card(j.page));
  console.log('Edda card', await card(d.page));
  await L.shot(j.page, 'g02_jonah_card');
  await L.shot(d.page, 'g03_edda_card');
  console.log('Jonah focused', await j.page.evaluate(() => document.activeElement?.innerText));
  await sleep(35000);
  console.log('Jonah card at ~36s', await card(j.page));
  await L.shot(j.page, 'g04_jonah_card_36s');
  await j.page.locator('[role=alertdialog] button', { hasText: 'Intercept' }).tap();
  await sleep(3000);
  console.log('after intercept: Imogen', H.char(state.chars.a.id).body_marks, 'Jonah', H.char(state.chars.b.id).body_marks, 'nerve', H.char(state.chars.b.id).nerve_current);
  console.log('Edda card after', await card(d.page));
  console.log('LK new lines', (await H.log(lk.page)).slice(n0));
  console.log('Jonah log tail', (await H.log(j.page)).slice(-3));
  await L.shot(j.page, 'g05_jonah_after');
  console.log('errors', a.errors, j.errors, d.errors);
  await b.close();
})();
